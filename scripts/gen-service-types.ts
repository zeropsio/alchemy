import * as Effect from "effect/Effect";
import * as Redacted from "effect/Redacted";
import { makeHttp } from "../src/client/Http.ts";
import type { components } from "../src/client/api.gen.ts";

type Entry = { name: string; versionName: string; status: string; category: string };
const snapshot = new URL("../spec/service-types.json", import.meta.url);
if (process.argv.includes("--fetch")) {
  const endpoint = process.env.ZEROPS_ENDPOINT ?? "https://api.app-prg1.zerops.io";
  const http = makeHttp({ endpoint, token: Redacted.make(process.env.ZEROPS_TOKEN!) });
  const settings = await Effect.runPromise(
    http.request<components["schemas"]["ResponseSettings"]>("GET", "/settings"),
  );
  const entries: Entry[] = settings.serviceStackList.flatMap((type) =>
    type.serviceStackTypeVersionList.map((version) => ({
      name: type.name,
      versionName: version.name,
      status: version.status,
      category: type.category,
    })),
  );
  entries.sort((a, b) => a.versionName.localeCompare(b.versionName));
  await Bun.write(snapshot, JSON.stringify(entries, null, 2) + "\n");
}
const entries = (await Bun.file(snapshot).json()) as Entry[];
const names = [
  ...new Set(
    entries.filter((entry) => entry.status === "ACTIVE").map((entry) => entry.versionName),
  ),
].sort();
const modeFamilies = [
  ...new Set(names.filter((name) => name.includes(":single@")).map((name) => name.split(":")[0])),
].sort();
await Bun.write(
  new URL("../src/client/serviceTypes.gen.ts", import.meta.url),
  "// Generated by scripts/gen-service-types.ts from spec/service-types.json.\n" +
    "export type KnownServiceType =\n" +
    names.map((name) => "  | " + JSON.stringify(name)).join("\n") +
    ";\n" +
    "export const serviceTypesWithModes: ReadonlySet<string> = new Set([\n" +
    modeFamilies.map((name) => "  " + JSON.stringify(name) + ",").join("\n") +
    "\n]);\n",
);
console.log(
  JSON.stringify({
    versions: entries.length,
    active: names.length,
    families: new Set(entries.map((entry) => entry.name)).size,
  }),
);
